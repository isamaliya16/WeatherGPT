export function getLanguageByCode(code: string): IndianLanguage {
  const found = INDIAN_LANGUAGES.find(l => l.code === code);
  return found || INDIAN_LANGUAGES[0]; // fallback to Gujarati or Hindi/English
}

export function detectLanguageFromText(text: string): IndianLanguage {
  const t = text.trim();
  const lower = t.toLowerCase();

  // 1. Native Indic Script Matching (Primary)
  if (/[\u0A80-\u0AFF]/.test(t)) return getLanguageByCode('gu'); // Gujarati
  if (/[\u0900-\u097F]/.test(t)) {
    if (t.includes('पाऊस') || t.includes('आहे') || t.includes('कधी') || t.includes('फवारणी')) return getLanguageByCode('mr');
    if (t.includes('अहाँक') || t.includes('बरखा') || t.includes('लेल')) return getLanguageByCode('mai');
    if (t.includes('तुंदा') || t.includes('कन्नै')) return getLanguageByCode('doi');
    if (t.includes('सस्य') || t.includes('वृष्टिः')) return getLanguageByCode('sa');
    return getLanguageByCode('hi'); // Default Devanagari is Hindi
  }
  if (/[\u0980-\u09FF]/.test(t)) {
    if (t.includes('হ’বনে') || t.includes('বতৰ') || t.includes('বানપানীৰ')) return getLanguageByCode('as');
    return getLanguageByCode('bn'); // Bengali
  }
  if (/[\u0B80-\u0BFF]/.test(t)) return getLanguageByCode('ta'); // Tamil
  if (/[\u0C00-\u0C7F]/.test(t)) return getLanguageByCode('te'); // Telugu
  if (/[\u0C80-\u0CFF]/.test(t)) return getLanguageByCode('kn'); // Kannada
  if (/[\u0D00-\u0D7F]/.test(t)) return getLanguageByCode('ml'); // Malayalam
  if (/[\u0B00-\u0B7F]/.test(t)) return getLanguageByCode('or'); // Odia
  if (/[\u0A00-\u0A7F]/.test(t)) return getLanguageByCode('pa'); // Punjabi
  if (/[\u0600-\u06FF]/.test(t)) {
    if (t.includes('پگاہ') || t.includes('رۄد')) return getLanguageByCode('ks');
    if (t.includes('ڪيترا') || t.includes('سڀاڻي')) return getLanguageByCode('sd');
    return getLanguageByCode('ur'); // Urdu
  }
  if (/[\u1C50-\u1C7F]/.test(t)) return getLanguageByCode('sat'); // Santali
  if (/[\uABC0-\uABFF]/.test(t)) return getLanguageByCode('mni'); // Manipuri

  // 2. Romanized Gujarati Detection
  if (
    /\b(varsad|varshad|chhe|kem|kare|aaje|kale|havaman|tamare|tamne|khedut|kharab|bahar)\b/i.test(lower) ||
    lower.includes('varsad') || lower.includes('varshad') || lower.includes('kem chho')
  ) {
    return getLanguageByCode('gu');
  }

  // 3. Romanized Hindi Detection
  if (
    /\b(kya|hogi|hoga|barish|barsaat|mausam|kaisa|kaise|rahega|aaj|kal|batao|bataye|kisan|kheti|surat me|delhi me|pani)\b/i.test(lower) ||
    lower.includes('barish') || lower.includes('mausam kaisa')
  ) {
    return getLanguageByCode('hi');
  }

  // 4. Default to English for Latin-based text
  return getLanguageByCode('en');
}
